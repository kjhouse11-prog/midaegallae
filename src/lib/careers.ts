// 전공별 데이터 요약 — 수록 대학·모집단위, 지역, 전형, 실기 종목, 평균 경쟁률
export function majorStats(list: Program[]) {
  const univs = new Set(list.map((p) => `${p.univ}${p.campus ? `(${p.campus})` : ""}`));
  const count = <T extends string>(xs: T[]) => Object.entries(xs.reduce((m, x) => ((m[x] = (m[x] || 0) + 1), m), {} as Record<string, number>)).sort((a, b) => b[1] - a[1]);
  const comps = list.map((p) => p.comp).filter((x): x is number => !!x);
  return {
    n: list.length, univ: univs.size,
    region: count(list.map((p) => (p.region === "서울" ? "서울" : ["경기", "인천"].includes(p.region) ? "경기·인천" : "지방"))),
    exams: count(list.flatMap(examsOf)),
    comp: comps.length ? +(comps.reduce((s, x) => s + x, 0) / comps.length).toFixed(1) : null,
  };
}
